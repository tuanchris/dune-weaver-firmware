#!/usr/bin/env python3
"""Generate the ported-WLED-effect registry for the firmware AND the app.

Scans FluidNC/src/WledFx/fx_*.cpp for ported `uint16_t mode_x(void)` effects,
looks each up in WLED's own FX.cpp for its name, slider labels, color/palette
use, 1D/2D flag and defaults, and writes:

  FluidNC/src/WledFx/WledFxList.cpp           kFx[]: name, function, 2D, WLED defaults
  <app>/src/lib/wledfx/catalog.ts             the same + labels and which controls each reads

Names ($LED/Effect values) are WLED's, lowercased with "_" for spaces; they
are what NVS stores, so a name never changes once shipped. The order is WLED's
own, so it can change freely.

  curl -sL https://raw.githubusercontent.com/wled/WLED/v0.15.3/wled00/FX.cpp -o /tmp/FX.cpp
  python3 tools/gen_wled_fx.py --fx /tmp/FX.cpp [--app ../dune-weaver-mobile]
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fx_parity import FXDIR, ROOT, batch_modes, parse_meta  # noqa: E402

# Our own effects (Leds.cpp kOwnEffects): WLED names that would collide.
OWN = """off static rainbow breathe colorloop theater scan running sine gradient sinelon twinkle sparkle fire candle
meteor bouncing wipe dualscan juggle multicomet glitter dissolve ripple drip lightning fireworks plasma heartbeat strobe
police chase railway pacifica aurora pride colorwaves bpm ball""".split()


def key_of(label):
    k = label.lower().replace("+", " plus").replace("&", " ")
    k = re.sub(r"[^a-z0-9]+", "_", k).strip("_")
    return k


def registrations(fx_cpp):
    s = Path(fx_cpp).read_text(encoding="utf-8", errors="replace")
    data = dict(re.findall(r'static const char (_data_FX_MODE_\w+)\[\] PROGMEM = "([^"]*)";', s))
    return [(fn, parse_meta(data.get(d, ""))) for _, fn, d in re.findall(r"addEffect\((FX_MODE_\w+),\s*&(\w+),\s*(_data_FX_MODE_\w+)\)", s)]


def slider(label, fallback):
    """WLED slider label: '!' = the default name, '' = hidden."""
    if label is None or label == "":
        return None
    return fallback if label == "!" else label


def uses_of(m):
    sl = m["sliders"]
    u = {}
    cols = m["colors"]
    toks = ["!", "!", "!"] if cols is None else cols.split(",")
    if len(toks) > 0 and toks[0] != "":
        u["color"] = True
    if len(toks) > 1 and toks[1] != "":
        u["color2"] = True
    if m["palette"] is None or m["palette"] != "":
        u["palette"] = "wled"
    sp = slider(sl[0] if len(sl) > 0 else None, "Speed")
    ix = slider(sl[1] if len(sl) > 1 else None, "Intensity")
    if sp is None:
        u["speed"] = False
    elif sp != "Speed":
        u["speed"] = sp
    if ix is not None:
        u["intensity"] = ix
    return u


def ts_obj(d):
    parts = []
    for k, v in d.items():
        if isinstance(v, bool):
            parts.append(f"{k}: {'true' if v else 'false'}")
        elif isinstance(v, int):
            parts.append(f"{k}: {v}")
        else:
            parts.append(f"{k}: {repr(v)}")
    return "{ " + ", ".join(parts) + " }" if parts else "{}"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--fx", required=True)
    ap.add_argument("--app", default=str(ROOT.parent / "dune-weaver-mobile"))
    a = ap.parse_args()
    app = Path(a.app).resolve()

    ported = {}
    for cpp in sorted(FXDIR.glob("fx_*.cpp")):
        c, t = batch_modes(cpp, app / f"src/lib/wledfx/{cpp.stem}.ts")
        for fn in c:
            if fn not in t:
                raise SystemExit(f"{cpp.stem}: {fn} has no TS port yet")
            ported[fn] = cpp.stem

    rows = []
    for fn, m in registrations(a.fx):
        if fn not in ported:
            continue
        name = key_of(m["name"])
        if name in OWN:
            raise SystemExit(f"{fn}: name '{name}' collides with our own effect")
        d = m["defaults"]
        rows.append({
            "fn": fn, "batch": ported.pop(fn), "name": name, "label": m["name"], "is2D": m["is2D"],
            "c1": d.get("c1", 128), "c2": d.get("c2", 128), "c3": d.get("c3", 16),
            "checks": (1 if d.get("o1") else 0) | (2 if d.get("o2") else 0) | (4 if d.get("o3") else 0),
            "sx": d.get("sx", 128), "ix": d.get("ix", 128), "uses": uses_of(m),
        })
    if ported:
        raise SystemExit(f"not registered in WLED's FX.cpp: {sorted(ported)}")
    names = [r["name"] for r in rows]
    assert len(set(names)) == len(names), "duplicate effect name"
    assert len(OWN) + len(rows) < 255, "effect ids are 0..254 (255 = none)"

    cpp = [
        "// GENERATED by tools/gen_wled_fx.py from the fx_*.cpp ports + WLED v0.15.3's",
        "// FX.cpp metadata. Edit the ports or the script, not this file.",
        '#include "WledFxRunner.h"',
        "",
        "namespace wled {",
        "",
    ]
    cpp += [f"uint16_t {r['fn']}();" for r in rows]
    cpp += ["", "// name, effect, 2D, WLED's custom1..3 defaults, check1..3 defaults", "const FxInfo kFx[] = {"]
    cpp += [f'    {{ "{r["name"]}", {r["fn"]}, {str(r["is2D"]).lower()}, {r["c1"]}, {r["c2"]}, {r["c3"]}, {r["checks"]} }},' for r in rows]
    cpp += ["};", "const int kFxCount = sizeof(kFx) / sizeof(kFx[0]);", "", "}  // namespace wled", ""]
    (FXDIR / "WledFxList.cpp").write_text("\n".join(cpp))

    batches = sorted({r["batch"] for r in rows})
    ts = [
        "// GENERATED by dune-weaver-firmware/tools/gen_wled_fx.py from the fx_*.ts / fx_*.cpp",
        "// ports + WLED v0.15.3's FX.cpp metadata. Edit the ports or the script, not this file.",
        "import type { FxInfo } from './runner'",
    ]
    ts += [f"import * as {b} from './{b}'" for b in batches]
    ts += [
        "",
        "export interface WledFxDef {",
        "  /** $LED/Effect value */",
        "  name: string",
        "  label: string",
        "  info: FxInfo",
        "  /** Which controls it reads (LedInputs in api/board.ts) */",
        "  uses: { color?: boolean; color2?: boolean; palette?: 'wled'; speed?: string | false; intensity?: string }",
        "  /** WLED's slider defaults: what picking the effect resets them to */",
        "  defaults: { speed: number; intensity: number }",
        "}",
        "",
        "export const WLED_FX: readonly WledFxDef[] = [",
    ]
    for r in rows:
        info = f"{{ name: '{r['name']}', fn: {r['batch']}.{r['fn']}, is2D: {str(r['is2D']).lower()}, c1: {r['c1']}, c2: {r['c2']}, c3: {r['c3']}, checks: {r['checks']} }}"
        ts.append(f"  {{ name: '{r['name']}', label: {repr(r['label'])}, info: {info}, uses: {ts_obj(r['uses'])}, defaults: {{ speed: {r['sx']}, intensity: {r['ix']} }} }},")
    ts += ["]", ""]
    (app / "src/lib/wledfx/catalog.ts").write_text("\n".join(ts))
    print(f"{len(rows)} WLED effects -> {FXDIR / 'WledFxList.cpp'}, {app}/src/lib/wledfx/catalog.ts")


if __name__ == "__main__":
    main()
