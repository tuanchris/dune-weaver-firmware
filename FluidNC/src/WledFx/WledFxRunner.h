// Runs one ported WLED effect (WledFx.h) onto the strip: owns its pixel
// buffer and effect state, and maps a 2D effect's matrix onto the strip's
// outline.  No WLED macros leak out of here, so Leds.cpp can include it.
// Std-only; mirrored by dune-weaver-mobile/src/lib/wledfx/runner.ts.
#pragma once

#include <cstdint>

namespace wled {

struct Segment;

// One ported effect.  WLED's extra sliders/checkboxes are not exposed: each
// effect runs with the defaults its WLED metadata names.
struct FxInfo {
    const char* name;  // $LED/Effect value
    uint16_t (*fn)();  // WLED's mode_xxx(), returns its frame delay in ms
    bool    is2D;      // draws on a kMatrix x kMatrix grid
    uint8_t c1, c2, c3;
    uint8_t checks;  // bit 0..2 = check1..3
};

// The registry (WledFxList.cpp, generated by tools/gen_wled_fx.py).
extern const FxInfo kFx[];
extern const int    kFxCount;

constexpr int kMatrix = 16;  // 2D effects: a 16 x 16 matrix (~a 49-LED ring's circumference)

struct FxFrame {
    uint8_t  speed, intensity;
    uint32_t color1, color2;  // 0xRRGGBB
    uint8_t  palette;         // $LED/Palette id; 0 = WLED's Default
    uint32_t now;             // ms
    bool     ring;            // strip is a circle (ThetaRho), else a rectangle's outline
};

class Runner {
public:
    // Draws one frame of `fx` into rgb (n LEDs x R,G,B).  Effect state persists
    // across calls; another fx (or n) restarts it, as WLED does on a mode
    // change.  False = no memory for it (rgb untouched).
    bool render(const FxInfo& fx, const FxFrame& f, uint8_t* rgb, int n);
    void release();  // frees the buffers (no WLED effect is showing)
    ~Runner() { release(); }

private:
    Segment*      _seg = nullptr;
    const FxInfo* _fx  = nullptr;
    int           _n   = 0;
};

void seed(uint16_t s);  // the effects' shared RNG

}  // namespace wled
